import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const workspace = resolve(import.meta.dirname, '..');
const manifestPath = join(workspace, 'package.json');
const versionsPath = join(workspace, 'src/lib/npmPackageVersions.ts');
const packages = ['oracle-insight-guard', 'verify-insight-receipt'];

function latestVersion(packageName) {
  const output = execFileSync('npm', ['view', packageName, 'dist-tags.latest', '--json'], {
    cwd: workspace,
    encoding: 'utf8',
  });
  const version = JSON.parse(output);
  if (typeof version !== 'string' || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`npm returned an invalid latest version for ${packageName}`);
  }
  return version;
}

const versions = Object.fromEntries(
  packages.map((packageName) => [packageName, latestVersion(packageName)])
);
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const verifierVersion = versions['verify-insight-receipt'];

if (manifest.dependencies?.['verify-insight-receipt'] !== verifierVersion) {
  execFileSync('npm', ['install', '--save-exact', `verify-insight-receipt@${verifierVersion}`], {
    cwd: workspace,
    stdio: 'inherit',
  });
}

const generated = `/** Generated by scripts/sync-npm-releases.mjs. Do not edit manually. */
export const ORACLE_INSIGHT_GUARD_VERSION = '${versions['oracle-insight-guard']}';
export const VERIFY_INSIGHT_RECEIPT_VERSION = '${verifierVersion}';
`;

writeFileSync(versionsPath, generated);
process.stdout.write(
  `Synced npm releases: oracle-insight-guard@${versions['oracle-insight-guard']}, verify-insight-receipt@${verifierVersion}\n`
);
